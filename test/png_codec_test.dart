const _iend = ('IEND', <int>[]);

List<int> _rgba(final Color color) => [
  color.red,
  color.green,
  color.blue,
  color.alpha,
];

/// An IHDR chunk; RGBA at 8 bits, no interlace, unless overridden.
(String, List<int>) _ihdr(
  final int width,
  final int height, {
  final int depth = 8,
  final int colour = 6,
  final int compression = 0,
  final int filter = 0,
  final int interlace = 0,
}) {
  final data = ByteData(13)
    ..setUint32(0, width)
    ..setUint32(4, height)
    ..setUint8(8, depth)
    ..setUint8(9, colour)
    ..setUint8(10, compression)
    ..setUint8(11, filter)
    ..setUint8(12, interlace);
  return ('IHDR', data.buffer.asUint8List());
}

/// A zlib stream holding [raw] in one stored block.
List<int> _zlib(final List<int> raw) {
  var a = 1;
  var b = 0;
  for (final byte in raw) {
    a = (a + byte) % 65521;
    b = (b + a) % 65521;
  }
  final length = raw.length;
  return [
    0x78, 0x01, // header
    0x01, length & 0xFF, length >> 8, ~length & 0xFF, (~length >> 8) & 0xFF,
    ...raw,
    b >> 8, b & 0xFF, a >> 8, a & 0xFF,
  ];
}

/// A PNG file made of [chunks], each with a correct length and CRC.
Uint8List _png(final List<(String, List<int>)> chunks) {
  final builder = BytesBuilder()..add([137, 80, 78, 71, 13, 10, 26, 10]);
  for (final (type, data) in chunks) {
    final body = [...type.codeUnits, ...data];
    builder
      ..add((ByteData(4)..setUint32(0, data.length)).buffer.asUint8List())
      ..add(body)
      ..add((ByteData(4)..setUint32(0, _crc(body))).buffer.asUint8List());
  }
  return builder.takeBytes();
}

int _crc(final List<int> bytes) {
  var crc = 0xFFFFFFFF;
  for (final byte in bytes) {
    crc ^= byte;
    for (var bit = 0; bit < 8; bit++) {
      crc = (crc & 1) != 0 ? 0xEDB88320 ^ (crc >> 1) : crc >> 1;
    }
  }
  return crc ^ 0xFFFFFFFF;
}
