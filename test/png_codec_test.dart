void main() {
  group('PngCodec', () {
    test('can encode and decode simple PNG', () {
      // Create a test image with various colors
      final bitmap = Bitmap(4, 4);

      // Set different colors in each quadrant
      // Top-left: Red
      bitmap.plot(0, 0, Color.fromRGBA(255, 0, 0, 255));
      bitmap.plot(1, 0, Color.fromRGBA(255, 0, 0, 255));
      bitmap.plot(0, 1, Color.fromRGBA(255, 0, 0, 255));
      bitmap.plot(1, 1, Color.fromRGBA(255, 0, 0, 255));

      // Top-right: Green
      bitmap.plot(2, 0, Color.fromRGBA(0, 255, 0, 255));
      bitmap.plot(3, 0, Color.fromRGBA(0, 255, 0, 255));
      bitmap.plot(2, 1, Color.fromRGBA(0, 255, 0, 255));
      bitmap.plot(3, 1, Color.fromRGBA(0, 255, 0, 255));

      // Bottom-left: Blue
      bitmap.plot(0, 2, Color.fromRGBA(0, 0, 255, 255));
      bitmap.plot(1, 2, Color.fromRGBA(0, 0, 255, 255));
      bitmap.plot(0, 3, Color.fromRGBA(0, 0, 255, 255));
      bitmap.plot(1, 3, Color.fromRGBA(0, 0, 255, 255));

      // Bottom-right: Yellow with transparency
      bitmap.plot(2, 2, Color.fromRGBA(255, 255, 0, 128));
      bitmap.plot(3, 2, Color.fromRGBA(255, 255, 0, 128));
      bitmap.plot(2, 3, Color.fromRGBA(255, 255, 0, 128));
      bitmap.plot(3, 3, Color.fromRGBA(255, 255, 0, 128));

      // Encode to PNG
      final codec = PngImageCodec();
      final encoded = codec.encode(bitmap);

      // Check PNG signature
      expect(encoded.length, greaterThan(8));
      expect(encoded[0], 137); // PNG signature
      expect(encoded[1], 80); // 'P'
      expect(encoded[2], 78); // 'N'
      expect(encoded[3], 71); // 'G'

      // Decoding returns exactly the encoded pixels
      final decoded = ok(codec.decode(encoded));
      expect([decoded.width, decoded.height], equals([4, 4]));
      for (var y = 0; y < 4; y++) {
        for (var x = 0; x < 4; x++) {
          expect(
            _rgba(decoded.pixel(x, y)),
            equals(_rgba(bitmap.pixel(x, y))),
            reason: '($x, $y)',
          );
        }
      }
    });

    test('canDecode correctly identifies PNG format', () {
      final codec = PngImageCodec();

      // Valid PNG signature
      final pngBytes = Uint8List.fromList([137, 80, 78, 71, 13, 10, 26, 10]);
      expect(codec.canDecode(pngBytes), isTrue);

      // Invalid data
      final invalidBytes = Uint8List.fromList([0, 1, 2, 3, 4, 5, 6, 7]);
      expect(codec.canDecode(invalidBytes), isFalse);

      // Too short
      final shortBytes = Uint8List.fromList([137, 80]);
      expect(codec.canDecode(shortBytes), isFalse);
    });

    test('PNG encoder creates valid file structure', () {
      final bitmap = Bitmap(2, 2);
      bitmap.plot(0, 0, Color.fromRGBA(255, 0, 0, 255));
      bitmap.plot(1, 0, Color.fromRGBA(0, 255, 0, 255));
      bitmap.plot(0, 1, Color.fromRGBA(0, 0, 255, 255));
      bitmap.plot(1, 1, Color.fromRGBA(255, 255, 255, 255));

      final codec = PngImageCodec();
      final encoded = codec.encode(bitmap);

      // Parse chunks manually
      int offset = 8; // Skip signature

      // First chunk should be IHDR
      final ihdrLength =
          (encoded[offset] << 24) |
          (encoded[offset + 1] << 16) |
          (encoded[offset + 2] << 8) |
          encoded[offset + 3];
      offset += 4;

      final ihdrType = String.fromCharCodes(
        encoded.sublist(offset, offset + 4),
      );
      expect(ihdrType, 'IHDR');
      offset += 4;

      // Check IHDR data
      final ihdrData = encoded.sublist(offset, offset + ihdrLength);
      final width =
          (ihdrData[0] << 24) |
          (ihdrData[1] << 16) |
          (ihdrData[2] << 8) |
          ihdrData[3];
      final height =
          (ihdrData[4] << 24) |
          (ihdrData[5] << 16) |
          (ihdrData[6] << 8) |
          ihdrData[7];

      expect(width, 2);
      expect(height, 2);
      expect(ihdrData[8], 8); // Bit depth
      expect(ihdrData[9], 6); // Color type (RGBA)
    });
  });

  group('Colour types and bit depths', () {
    final codec = PngImageCodec();
    // Generated by tool/make_png_fixtures.py, each with the expected 8-bit
    // RGBA pixels in a .rgba file
    const names = [
      'gray1', 'gray2', 'gray4', 'gray8', 'gray16', //
      'rgb8', 'rgb16',
      'palette1', 'palette2', 'palette4', 'palette8',
      'gray-alpha8', 'gray-alpha16',
      'rgba8', 'rgba16',
      'gray4-trns', 'gray16-trns', 'rgb8-trns', 'rgb16-trns',
      'palette2-trns', 'palette8-trns',
    ];
    for (final name in names) {
      test('$name.png decodes to the expected pixels', () {
        final bitmap = ok(
          codec.decode(File('test/fixtures/png/$name.png').readAsBytesSync()),
        );
        final expected = File('test/fixtures/png/$name.rgba').readAsBytesSync();
        expect([bitmap.width, bitmap.height], equals([16, 16]));
        for (var y = 0; y < 16; y++) {
          for (var x = 0; x < 16; x++) {
            final index = (y * 16 + x) * 4;
            expect(
              _rgba(bitmap.pixel(x, y)),
              equals(expected.sublist(index, index + 4)),
              reason: '($x, $y)',
            );
          }
        }
      });
    }
  });

  group('Adam7 interlacing', () {
    final codec = PngImageCodec();
    // Interlaced fixtures and their non-interlaced twins, with the expected
    // pixels in the twin's .rgba file
    const names = [
      'rgba8-16x16',
      'gray1-13x11',
      'palette4-13x11',
      'rgb16-trns-9x7',
      'gray-alpha8-3x2',
      'rgb8-1x1',
    ];
    for (final name in names) {
      test('adam7-$name.png decodes like its non-interlaced twin', () {
        final expected = File(
          'test/fixtures/png/adam7-$name-flat.rgba',
        ).readAsBytesSync();
        for (final file in ['adam7-$name', 'adam7-$name-flat']) {
          final bitmap = ok(
            codec.decode(File('test/fixtures/png/$file.png').readAsBytesSync()),
          );
          expect(bitmap.width * bitmap.height * 4, equals(expected.length));
          for (var y = 0; y < bitmap.height; y++) {
            for (var x = 0; x < bitmap.width; x++) {
              final index = (y * bitmap.width + x) * 4;
              expect(
                _rgba(bitmap.pixel(x, y)),
                equals(expected.sublist(index, index + 4)),
                reason: '$file ($x, $y)',
              );
            }
          }
        }
      });
    }
  });

  group('Compressed image data', () {
    final codec = PngImageCodec();

    for (final name in [
      'rgba8-stored',
      'rgba8-fixed',
      'rgba8-dynamic',
      // One per row filter type, and RGB cycling through all five
      'rgba8-none',
      'rgba8-sub',
      'rgba8-up',
      'rgba8-average',
      'rgba8-paeth',
      'rgb8-mixed',
    ]) {
      test('$name.png decodes pixel-exact', () {
        final bytes = File('test/fixtures/png/$name.png').readAsBytesSync();
        final bitmap = ok(codec.decode(bytes));
        final alpha = name.startsWith('rgba');
        expect([bitmap.width, bitmap.height], equals([16, 16]));
        for (var y = 0; y < 16; y++) {
          for (var x = 0; x < 16; x++) {
            // The pixel formula of tool/make_png_fixtures.py
            expect(
              _rgba(bitmap.pixel(x, y)),
              equals([
                x * 16,
                y * 16,
                (x * y) & 0xFF,
                alpha ? 255 - x * 8 : 255,
              ]),
              reason: '($x, $y)',
            );
          }
        }
      });
    }

    test('image data that inflates past the image size is a limit error', () {
      // 10 MB of zeros compressed into a 1x1 image
      final stream = ZLibEncoder(
        level: 1,
        strategy: ZLibOption.strategyFixed,
      ).convert(List.filled(10 << 20, 0));
      final watch = Stopwatch()..start();
      err(
        codec.decode(_png([_ihdr(1, 1), ('IDAT', stream), _iend])),
        ErrorKind.limit,
      );
      expect(watch.elapsedMilliseconds, lessThan(1000));
    });

    test('a wrong Adler-32 checksum is malformed', () {
      final stream = _zlib([0, 1, 2, 3, 4])..last ^= 1;
      err(
        codec.decode(_png([_ihdr(1, 1), ('IDAT', stream), _iend])),
        ErrorKind.malformed,
      );
    });
  });

  group('PNG validation', () {
    final codec = PngImageCodec();
    // Two RGBA pixels per row, two rows, no filtering
    final rows = [
      [0, 255, 0, 0, 255, 0, 255, 0, 255],
      [0, 0, 0, 255, 255, 255, 255, 255, 128],
    ];
    final pixels = [for (final row in rows) ...row];

    ErrorDetails decodeError(
      final List<(String, List<int>)> chunks,
      final ErrorKind kind,
    ) => err(codec.decode(_png(chunks)), kind);

    test('a valid stored PNG decodes', () {
      final bitmap = ok(
        codec.decode(_png([_ihdr(2, 2), ('IDAT', _zlib(pixels)), _iend])),
      );
      expect(_rgba(bitmap.pixel(0, 0)), equals([255, 0, 0, 255]));
      expect(_rgba(bitmap.pixel(1, 1)), equals([255, 255, 255, 128]));
    });

    test('bad CRC is malformed', () {
      final bytes = _png([_ihdr(2, 2), ('IDAT', _zlib(pixels)), _iend]);
      bytes[8 + 4 + 4 + 13] ^= 1; // first byte of the IHDR CRC
      final details = err(codec.decode(bytes), ErrorKind.malformed);
      expect(details.message, contains('CRC'));
    });

    test('a chunk before IHDR is malformed', () {
      final details = decodeError([
        ('IDAT', _zlib(pixels)),
        _ihdr(2, 2),
        _iend,
      ], ErrorKind.malformed);
      expect(details.message, contains('IHDR'));
    });

    test('a second IHDR is malformed', () {
      decodeError([
        _ihdr(2, 2),
        _ihdr(2, 2),
        ('IDAT', _zlib(pixels)),
        _iend,
      ], ErrorKind.malformed);
    });

    test('invalid IHDR fields are malformed', () {
      final cases = <String, (String, List<int>)>{
        'length': ('IHDR', _ihdr(2, 2).$2.sublist(0, 12)),
        'zero width': _ihdr(0, 2),
        'zero height': _ihdr(2, 0),
        'width over 2^31-1': _ihdr(0x80000000, 2),
        'depth for colour type': _ihdr(2, 2, depth: 4),
        'colour type': _ihdr(2, 2, colour: 5),
        'compression method': _ihdr(2, 2, compression: 1),
        'filter method': _ihdr(2, 2, filter: 1),
        'interlace method': _ihdr(2, 2, interlace: 2),
      };
      for (final MapEntry(key: name, value: header) in cases.entries) {
        final result = codec.decode(
          _png([header, ('IDAT', _zlib(pixels)), _iend]),
        );
        expect(
          result,
          isA<Err<Bitmap, ErrorDetails>>().having(
            (error) => error.error.kind,
            'kind',
            ErrorKind.malformed,
          ),
          reason: name,
        );
      }
    });

    test('palette and transparency chunk errors are malformed', () {
      // A 2x2 8-bit palette image using indices 0 to 3
      final indices = _zlib([0, 0, 1, 0, 2, 3]);
      final palette = ('PLTE', List.filled(12, 9));
      final cases = <String, List<(String, List<int>)>>{
        'palette image without PLTE': [
          _ihdr(2, 2, colour: 3),
          ('IDAT', indices),
        ],
        'PLTE not a multiple of 3': [
          _ihdr(2, 2, colour: 3),
          ('PLTE', List.filled(11, 9)),
          ('IDAT', indices),
        ],
        'PLTE over 256 entries': [
          _ihdr(2, 2, colour: 3),
          ('PLTE', List.filled(771, 9)),
          ('IDAT', indices),
        ],
        'index beyond the palette': [
          _ihdr(2, 2, colour: 3),
          ('PLTE', List.filled(9, 9)),
          ('IDAT', indices),
        ],
        'PLTE after IDAT': [_ihdr(2, 2, colour: 3), ('IDAT', indices), palette],
        'second PLTE': [_ihdr(2, 2, colour: 3), palette, palette],
        'PLTE in a greyscale image': [
          _ihdr(2, 2, colour: 0),
          palette,
          ('IDAT', _zlib([0, 0, 0, 0, 0, 0])),
        ],
        'tRNS longer than the palette': [
          _ihdr(2, 2, colour: 3),
          palette,
          ('tRNS', [1, 2, 3, 4, 5]),
          ('IDAT', indices),
        ],
        'tRNS of the wrong length for greyscale': [
          _ihdr(2, 2, colour: 0),
          ('tRNS', [0]),
          ('IDAT', _zlib([0, 0, 0, 0, 0, 0])),
        ],
        'tRNS of the wrong length for RGB': [
          _ihdr(1, 1, colour: 2),
          ('tRNS', [0, 0, 0, 0]),
          ('IDAT', _zlib([0, 0, 0, 0])),
        ],
        'tRNS with an alpha channel': [
          _ihdr(2, 2),
          ('tRNS', [0, 0]),
          ('IDAT', _zlib(pixels)),
        ],
        'tRNS before PLTE': [
          _ihdr(2, 2, colour: 3),
          ('tRNS', [1]),
          palette,
          ('IDAT', indices),
        ],
        'second tRNS': [
          _ihdr(2, 2, colour: 0),
          ('tRNS', [0, 0]),
          ('tRNS', [0, 0]),
          ('IDAT', _zlib([0, 0, 0, 0, 0, 0])),
        ],
      };
      for (final MapEntry(key: name, value: chunks) in cases.entries) {
        final result = codec.decode(_png([...chunks, _iend]));
        expect(result, isA<Err<Bitmap, ErrorDetails>>(), reason: name);
        expect(
          (result as Err<Bitmap, ErrorDetails>).error.kind,
          equals(ErrorKind.malformed),
          reason: '$name: ${result.error.message}',
        );
      }
    });

    test('invalid dynamic Huffman code lengths are malformed', () {
      // Final dynamic block (BTYPE 10) whose code-length code has no codes
      decodeError([
        _ihdr(2, 2),
        ('IDAT', [0x78, 0x01, 0x05, 0x00, 0, 0, 0, 1]),
        _iend,
      ], ErrorKind.malformed);
    });

    test('Paeth ties prefer left over corner, and up over corner', () {
      // Red at (1, 1): left 10, up 40, corner 20 ties up with corner.
      // Green at (1, 1): left 40, up 10, corner 20 ties left with corner.
      // Both decode to 100 only if the tie is broken as the PNG spec says
      final raw = [
        0, 20, 20, 0, 40, 10, 0, // None
        4, 246, 20, 0, 60, 60, 0, // Paeth: (0, 1) predicted from up
      ];
      final bitmap = ok(
        codec.decode(
          _png([_ihdr(2, 2, colour: 2), ('IDAT', _zlib(raw)), _iend]),
        ),
      );
      expect(_rgba(bitmap.pixel(0, 1)), equals([10, 40, 0, 255]));
      expect(_rgba(bitmap.pixel(1, 1)), equals([100, 100, 0, 255]));
    });

    test('a row filter type above 4 is malformed', () {
      final filtered = [...pixels]..[9] = 5; // second row
      final details = decodeError([
        _ihdr(2, 2),
        ('IDAT', _zlib(filtered)),
        _iend,
      ], ErrorKind.malformed);
      expect(details.message, contains('filter'));
    });

    test('a chunk longer than the remaining bytes is truncated', () {
      final bytes = _png([_ihdr(2, 2), ('IDAT', _zlib(pixels)), _iend]);
      // IDAT length field follows the signature and the 25-byte IHDR chunk
      ByteData.sublistView(bytes).setUint32(8 + 25, 1 << 20);
      err(codec.decode(bytes), ErrorKind.truncated);
    });

    test('a missing IEND is truncated', () {
      decodeError([_ihdr(2, 2), ('IDAT', _zlib(pixels))], ErrorKind.truncated);
    });

    test('too little image data is malformed', () {
      decodeError([
        _ihdr(2, 2),
        ('IDAT', _zlib(pixels.sublist(0, 12))),
        _iend,
      ], ErrorKind.malformed);
    });

    test('8000 one-byte IDAT chunks decode', () {
      const width = 50;
      const height = 40;
      final raw = [
        for (var y = 0; y < height; y++) ...[
          0,
          for (var x = 0; x < width; x++) ...[x, y, 7, 255],
        ],
      ];
      final stream = _zlib(raw);
      expect(stream.length, greaterThan(8000));
      final bitmap = ok(
        codec.decode(
          _png([
            _ihdr(width, height),
            for (final byte in stream) ('IDAT', [byte]),
            _iend,
          ]),
        ),
      );
      expect(_rgba(bitmap.pixel(49, 39)), equals([49, 39, 7, 255]));
    });
  });

  group('Integer Blend Modes', () {
    test('srcOver blending matches expected results', () {
      // Test integer-based srcOver blending
      final src = Color.fromRGBA(255, 0, 0, 128); // Semi-transparent red
      final dst = Color.fromRGBA(0, 0, 255, 255); // Opaque blue

      final result = BlendModes.blend(src, dst, BlendMode.srcOver);

      // Should be reddish-purple
      expect(result.alpha, 255); // Result should be opaque
      expect(result.red, greaterThan(100)); // Some red
      expect(result.blue, greaterThan(100)); // Some blue preserved
      expect(result.green, 0); // No green
    });

    test('all blend modes produce valid colors', () {
      final src = Color.fromRGBA(150, 100, 200, 180);
      final dst = Color.fromRGBA(100, 150, 50, 200);

      final modes = [
        BlendMode.clear,
        BlendMode.src,
        BlendMode.dst,
        BlendMode.srcOver,
        BlendMode.dstOver,
        BlendMode.srcIn,
        BlendMode.dstIn,
        BlendMode.srcOut,
        BlendMode.dstOut,
        BlendMode.srcAtop,
        BlendMode.dstAtop,
        BlendMode.xor,
        BlendMode.add,
        BlendMode.multiply,
        BlendMode.screen,
        BlendMode.overlay,
        BlendMode.darken,
        BlendMode.lighten,
        BlendMode.colorDodge,
        BlendMode.colorBurn,
        BlendMode.hardLight,
        BlendMode.softLight,
        BlendMode.difference,
        BlendMode.exclusion,
      ];

      for (final mode in modes) {
        final result = BlendModes.blend(src, dst, mode);

        // Check all channels are valid
        expect(
          result.alpha,
          inInclusiveRange(0, 255),
          reason: 'Alpha out of range for $mode',
        );
        expect(
          result.red,
          inInclusiveRange(0, 255),
          reason: 'Red out of range for $mode',
        );
        expect(
          result.green,
          inInclusiveRange(0, 255),
          reason: 'Green out of range for $mode',
        );
        expect(
          result.blue,
          inInclusiveRange(0, 255),
          reason: 'Blue out of range for $mode',
        );
      }
    });
  });
