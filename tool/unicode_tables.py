#!/usr/bin/env python3
"""Generates lib/src/text/unicode_tables.dart from Python's unicodedata.

Run from the repository root: python3 tool/unicode_tables.py

The tables:
- bidi classes, as runs of code points sharing a class, collapsed to the
  classes the simplified bidi algorithm uses: explicit embeddings, overrides
  and isolates become ON, and unassigned code points take the default of
  their block (R or AL in the right-to-left blocks, L elsewhere);
- the Arabic presentation forms of each letter (isolated, final, initial,
  medial), read from the compatibility decompositions of U+FB50-FEFF, and
  the lam-alef ligatures;
- mirrored bracket pairs, for right-to-left runs.
Uses only the Python standard library.
"""

import unicodedata
from pathlib import Path

OUTPUT = Path('lib/src/text/unicode_tables.dart')

CLASSES = ['L', 'R', 'AL', 'EN', 'ES', 'ET', 'AN', 'CS', 'NSM', 'BN', 'B',
           'S', 'WS', 'ON']

# Default classes of unassigned code points (DerivedBidiClass.txt)
DEFAULT_R = [(0x0590, 0x05FF), (0x07C0, 0x085F), (0xFB1D, 0xFB4F),
             (0x10800, 0x10CFF), (0x10D40, 0x10EBF), (0x10F00, 0x10F2F),
             (0x10F70, 0x10FFF), (0x1E800, 0x1EC6F), (0x1ECC0, 0x1ECFF),
             (0x1ED50, 0x1EDFF), (0x1EF00, 0x1EFFF)]
DEFAULT_AL = [(0x0600, 0x07BF), (0x0860, 0x08FF), (0xFB50, 0xFDCF),
              (0xFDF0, 0xFDFF), (0xFE70, 0xFEFF), (0x10D00, 0x10D3F),
              (0x10EC0, 0x10EFF), (0x10F30, 0x10F6F), (0x1EC70, 0x1ECBF),
              (0x1ED00, 0x1ED4F), (0x1EE00, 0x1EEFF)]

MIRRORS = '()<>[]{}«»‹›⁅⁆⁽⁾₍₎≤≥⟨⟩⟪⟫⦃⦄⦅⦆〈〉《》「」『』【】〔〕〖〗〘〙〚〛'

FORMS = ['<isolated>', '<final>', '<initial>', '<medial>']


def bidi(code):
    value = unicodedata.bidirectional(chr(code))
    if value in CLASSES:
        return value
    if value:
        return 'ON'  # explicit formatting characters
    for start, end in DEFAULT_R:
        if start <= code <= end:
            return 'R'
    for start, end in DEFAULT_AL:
        if start <= code <= end:
            return 'AL'
    return 'L'


def runs():
    starts, classes = [], []
    for code in range(0x110000):
        value = CLASSES.index(bidi(code))
        if not classes or classes[-1] != value:
            starts.append(code)
            classes.append(value)
    return starts, classes


def forms():
    letters, ligatures = {}, {}
    for code in range(0xFB50, 0xFF00):
        parts = unicodedata.decomposition(chr(code)).split()
        if len(parts) < 2 or parts[0] not in FORMS:
            continue
        form = FORMS.index(parts[0])
        bases = [int(part, 16) for part in parts[1:]]
        if len(bases) == 1:
            letters.setdefault(bases[0], [0, 0, 0, 0])
            letters[bases[0]][form] = letters[bases[0]][form] or code
        elif len(bases) == 2 and bases[0] == 0x0644 and code >= 0xFEF5:
            ligatures.setdefault(bases[1], [0, 0])
            ligatures[bases[1]][form] = code
    return letters, ligatures


def wrap(values, indent='  '):
    lines, line = [], indent
    for value in values:
        item = f'{value}, '
        if len(line) + len(item) > 80:
            lines.append(line.rstrip())
            line = indent
        line += item
    lines.append(line.rstrip())
    return '\n'.join(lines)


def main():
    starts, classes = runs()
    letters, ligatures = forms()
    pairs = [(ord(MIRRORS[i]), ord(MIRRORS[i + 1]))
             for i in range(0, len(MIRRORS), 2)]
    version = unicodedata.unidata_version
    hexed = lambda code: f'0x{code:04X}'
    text = f'''// Generated by tool/unicode_tables.py from Unicode {version}; do not edit.

/// Bidi classes of UAX #9, in the order [bidiClasses] numbers them
enum BidiClass {{ {', '.join(name.lower() for name in CLASSES)} }}

// dart format off

/// First code point of each run of code points that share a bidi class
const List<int> bidiStarts = [
{wrap(starts)}
];

/// The class of each run in [bidiStarts], as a [BidiClass] index
const List<int> bidiClasses = [
{wrap(classes)}
];

/// The presentation forms of each Arabic letter: isolated, final, initial
/// and medial, or 0 where the letter has no such form
const Map<int, List<int>> arabicForms = {{
{chr(10).join(f'  {hexed(base)}: [{", ".join(hexed(code) for code in letters[base])}],' for base in sorted(letters))}
}};

/// The lam-alef ligature of lam followed by each alef: isolated and final
const Map<int, List<int>> lamAlef = {{
{chr(10).join(f'  {hexed(alef)}: [{", ".join(hexed(code) for code in ligatures[alef])}],' for alef in sorted(ligatures))}
}};

/// Mirrored characters in pairs, each mapped to its mirror
const Map<int, int> mirrors = {{
{chr(10).join(f'  {hexed(a)}: {hexed(b)},{chr(10)}  {hexed(b)}: {hexed(a)},' for a, b in pairs)}
}};

// dart format on
'''
    OUTPUT.write_text(text)
    print(f'{OUTPUT}: {len(starts)} bidi runs, {len(letters)} letters, '
          f'{len(ligatures)} lam-alef ligatures, {len(pairs)} mirrored pairs')


if __name__ == '__main__':
    main()
